/// Bytes of the init sequence.
pub const INIT_BYTES: u32 = {
    let mut n = 0;
    let mut i = 0;
    while i < INIT.len() {
        n += 1 + INIT[i].1.len() as u32;
        i += 1;
    }
    n
};
/// CASET and RASET with four parameters each, then RAMWR.
pub const WINDOW_BYTES: u32 = 5 + 5 + 1;
/// DISPON, SLPOUT.
pub const WAKE_BYTES: u32 = 2;
