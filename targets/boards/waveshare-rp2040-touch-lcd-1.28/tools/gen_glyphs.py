"""Writes src/glyphs.rs: 11x11 one-bit bitmaps of the Japanese characters the
home screen uses, rasterised from Noto Sans JP Regular (SIL Open Font
License 1.1, see fonts/OFL-NotoSansJP.txt).

    python tools/gen_glyphs.py <NotoSansJP-Regular.ttf>

Needs Pillow. Add a character to CHARS when a screen word needs it; the
host test `every_word_has_its_glyphs` fails until the table has it.
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

CELL = 11
# Every Japanese character of the state and phase words in src/screen.rs.
CHARS = "確定試行中無応答巻戻し検証再起動拒否失敗署名不正鍵不一致非互換破損"
THRESHOLD = 110

out = pathlib.Path(__file__).resolve().parent.parent / "src" / "glyphs.rs"
font = ImageFont.truetype(sys.argv[1], CELL)
seen = []
rows_out = []
for ch in CHARS:
    if ch in seen:
        continue
    seen.append(ch)
    img = Image.new("L", (CELL, CELL), 0)
    d = ImageDraw.Draw(img)
    # Centre the ink box in the cell.
    l, t, r, b = d.textbbox((0, 0), ch, font=font)
    d.text(((CELL - (r - l)) // 2 - l, (CELL - (b - t)) // 2 - t), ch, font=font, fill=255)
    rows = []
    for y in range(CELL):
        bits = 0
        for x in range(CELL):
            if img.getpixel((x, y)) >= THRESHOLD:
                bits |= 1 << (CELL - 1 - x)
        rows.append(f"0x{bits:03X}")
    rows_out.append(f"    ('{ch}', [{', '.join(rows)}]),")

out.write_text(
    "// Generated by tools/gen_glyphs.py from Noto Sans JP Regular\n"
    "// (c) 2014-2021 Adobe, SIL Open Font License 1.1, see fonts/OFL-NotoSansJP.txt.\n"
    "// Do not edit by hand.\n\n"
    "//! 11x11 bitmaps of the Japanese characters the home screen uses: one\n"
    "//! row per `u16`, bit 10 the leftmost pixel.\n\n"
    f"pub const CELL: u32 = {CELL};\n\n"
    "#[rustfmt::skip]\n"
    "pub const GLYPHS: &[(char, [u16; 11])] = &[\n" + "\n".join(rows_out) + "\n];\n",
    encoding="utf-8",
    newline="\n",
)
print(f"{out}: {len(seen)} glyphs")
