"""Writes src/glyphs.rs: 14x14 one-bit bitmaps of exactly the characters of
the screen's words (the string literals of src/texts.rs), rasterised from
Noto Sans JP Regular (SIL Open Font License 1.1, see fonts/OFL-NotoSansJP.txt).

    python tools/gen_glyphs.py <NotoSansJP-Regular.ttf>

Needs Pillow. Run it again after changing a word; the host test
`the_glyphs_are_exactly_the_words_characters` fails until the table matches.
"""
import pathlib
import re
import sys

from PIL import Image, ImageDraw, ImageFont

# Keep in step with CELL in src/lib.rs (the test checks the table's rows).
CELL = 14
THRESHOLD = 110

src = pathlib.Path(__file__).resolve().parent.parent / "src"
words = re.findall(r'"([^"]*)"', (src / "texts.rs").read_text(encoding="utf-8"))
chars = list(dict.fromkeys(ch for w in words for ch in w))
font = ImageFont.truetype(sys.argv[1], CELL)
rows_out = []
for ch in chars:
    img = Image.new("L", (CELL, CELL), 0)
    d = ImageDraw.Draw(img)
    # Centre the ink box in the cell.
    l, t, r, b = d.textbbox((0, 0), ch, font=font)
    d.text(((CELL - (r - l)) // 2 - l, (CELL - (b - t)) // 2 - t), ch, font=font, fill=255)
    rows = []
    for y in range(CELL):
        bits = 0
        for x in range(CELL):
            if img.getpixel((x, y)) >= THRESHOLD:
                bits |= 1 << (CELL - 1 - x)
        rows.append(f"0x{bits:04X}")
    rows_out.append(f"    ('{ch}', [{', '.join(rows)}]),")

out = src / "glyphs.rs"
out.write_text(
    "// Generated by tools/gen_glyphs.py from Noto Sans JP Regular\n"
    "// (c) 2014-2021 Adobe, SIL Open Font License 1.1, see fonts/OFL-NotoSansJP.txt.\n"
    "// Do not edit by hand.\n\n"
    f"//! {CELL}x{CELL} bitmaps of the characters of src/texts.rs: one row per\n"
    f"//! `u16`, bit {CELL - 1} the leftmost pixel.\n\n"
    "#[rustfmt::skip]\n"
    f"pub const GLYPHS: &[(char, [u16; {CELL}])] = &[\n" + "\n".join(rows_out) + "\n];\n",
    encoding="utf-8",
    newline="\n",
)
print(f"{out}: {len(chars)} glyphs")
